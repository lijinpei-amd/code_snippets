install_node() {
    local nvm_tag nvm_url tmp node_version digest
    local cc_version cc_integ cx_version cx_integ

    export NVM_DIR="$HOME/.nvm"

    # Install/refresh nvm's own source tree at the latest release tag. The marker
    # records the installed tag so the source is only re-fetched when it changes;
    # installed Node versions and aliases under $NVM_DIR are preserved.
    nvm_tag=$(resolve_tag nvm nvm-sh/nvm) || return 1
    nvm_url="https://codeload.github.com/nvm-sh/nvm/tar.gz/${nvm_tag}"
    if [ ! -f "$NVM_DIR/.nvm-installed-tag" ] \
        || [ "$(cat "$NVM_DIR/.nvm-installed-tag")" != "$nvm_tag" ] \
        || [ ! -s "$NVM_DIR/nvm.sh" ]; then
        tmp=$(mktemp -d)
        mkdir "$tmp/staged"
        download "$nvm_url" "$tmp/nvm.tar.gz" || { rm -rf "$tmp"; return 1; }
        digest=$(sha256_of "$tmp/nvm.tar.gz")
        tar xzf "$tmp/nvm.tar.gz" --strip-components=1 -C "$tmp/staged" \
            || { rm -rf "$tmp"; return 1; }
        [ -s "$tmp/staged/nvm.sh" ] || {
            echo "error: nvm archive lacks nvm.sh" >&2
            rm -rf "$tmp"
            return 1
        }
        mkdir -p "$NVM_DIR"
        cp -a "$tmp/staged/." "$NVM_DIR/"
        printf '%s\n' "$nvm_tag" > "$NVM_DIR/.nvm-installed-tag"
        rm -rf "$tmp"
        record_lock nvm "$nvm_tag" "sha256:$digest"
    else
        record_lock nvm "$nvm_tag" -
    fi

    # shellcheck disable=SC1091
    [ -s "$NVM_DIR/nvm.sh" ] && \. "$NVM_DIR/nvm.sh"
    # Install Node.js and make it the default: the locked version under --locked,
    # otherwise the latest LTS ("lts/*" is resolved by nvm at runtime). The
    # default alias is written directly rather than via `nvm alias`: nvm install
    # is || -guarded (so errexit is suppressed inside it), but a bare `nvm alias`
    # would run with errexit active and could abort on a benign internal status.
    mkdir -p "$NVM_DIR/alias"
    if [ "$USE_LOCK" -eq 1 ]; then
        node_version=$(lock_version node) || return 1
        nvm install "$node_version" || return 1
        printf '%s\n' "$node_version" > "$NVM_DIR/alias/default"
        nvm use --silent "$node_version"
    else
        nvm install --lts || return 1
        printf 'lts/*\n' > "$NVM_DIR/alias/default"
        nvm use --lts --silent
    fi
    node_version=$(node --version)
    record_lock node "$node_version" -

    # Install the Claude Code and Codex CLIs. npm runs its own postinstall (which
    # fetches each tool's native binary); this replaces the former offline
    # pinned-tarball dance. Versions come from the lockfile under --locked.
    local cc_spec cx_spec
    if [ "$USE_LOCK" -eq 1 ]; then
        cc_version=$(lock_version claude-code) || return 1
        cx_version=$(lock_version codex) || return 1
        cc_spec="@anthropic-ai/claude-code@${cc_version}"
        cx_spec="@openai/codex@${cx_version}"
    else
        cc_spec="@anthropic-ai/claude-code@latest"
        cx_spec="@openai/codex@latest"
    fi
    npm install -g --no-audit --no-fund "$cc_spec" "$cx_spec" || return 1
    claude --version >/dev/null
    codex --version >/dev/null

    # Record resolved versions + registry integrity (sha512) for the lockfile.
    # Note: in the @latest case this re-queries the registry, so a publish in the
    # seconds between install and query could record a version newer than the one
    # just installed. Cosmetic only; the installed binaries are the source of truth.
    cc_version=$(npm view "$cc_spec" version 2>/dev/null || echo "")
    cc_integ=$(npm view "$cc_spec" dist.integrity 2>/dev/null || echo "")
    cx_version=$(npm view "$cx_spec" version 2>/dev/null || echo "")
    cx_integ=$(npm view "$cx_spec" dist.integrity 2>/dev/null || echo "")
    record_lock claude-code "${cc_version:-unknown}" "${cc_integ:+${cc_integ/-/:}}"
    record_lock codex "${cx_version:-unknown}" "${cx_integ:+${cx_integ/-/:}}"
}

config_claude() {
    json_patch ~/.claude.json '.hasCompletedOnboarding = true'
    # Durable Claude Code configuration is managed separately by chezmoi at
    # git@github.com:lijinpei-amd/dotfiles.git. Gateway settings and credentials
    # remain out-of-band (for example, exported from the personal ~/.env.sh).
}

install_gh() {
    case "$DISTRO" in
        # pacman installs the current repo version; --locked cannot pin it here.
        arch)
            pkg_install gh
            ;;
        debian)
            local keyring=/etc/apt/keyrings/githubcli-archive-keyring.gpg
            local sources=/etc/apt/sources.list.d/github-cli.list
            local key_url="https://cli.github.com/packages/githubcli-archive-keyring.gpg"
            local tmpdir
            pkg_install gnupg
            tmpdir=$(mktemp -d)
            as_root mkdir -p -m 755 /etc/apt/keyrings /etc/apt/sources.list.d
            download "$key_url" "$tmpdir/github-cli.gpg" \
                || { rm -rf "$tmpdir"; return 1; }
            # Identity check on the signing key (version-agnostic) is retained.
            verify_openpgp_fingerprints "$tmpdir/github-cli.gpg" \
                2C6106201985B60E6C7AC87323F3D4EA75716059 \
                7F38BBB59D064DBCB3D84D725612B36462313325 \
                || { rm -rf "$tmpdir"; return 1; }
            as_root install -m 0644 "$tmpdir/github-cli.gpg" "$keyring" \
                || { rm -rf "$tmpdir"; return 1; }
            rm -rf "$tmpdir"
            echo "deb [arch=$(dpkg --print-architecture) signed-by=$keyring] https://cli.github.com/packages stable main" \
                | as_root tee "$sources" >/dev/null
            as_root apt-get update
            local gh_pkg=gh
            if [ "$USE_LOCK" -eq 1 ]; then
                local gh_ver
                gh_ver=$(lock_version gh) || return 1
                # Best-effort pin: the recorded version comes from `gh --version`
                # and the apt package version may not match it exactly (suffix or
                # different formatting), and old builds age out of the repo. If the
                # exact version is not available, fall back to latest with a warning
                # rather than fail; gh is not reproducibly pinnable through apt.
                if apt-cache show "gh=${gh_ver}" >/dev/null 2>&1; then
                    gh_pkg="gh=${gh_ver}"
                else
                    echo "warn: gh $gh_ver no longer in apt repo; installing latest" >&2
                fi
            fi
            as_root env DEBIAN_FRONTEND=noninteractive apt-get install -y "$gh_pkg"
            ;;
    esac
    record_lock gh "$(gh --version 2>/dev/null | sed -n 's/^gh version \([0-9.]*\).*/\1/p' | head -1)" -
}

install_uv() {
    local version platform url tmp source_dir digest installed_version=""

    version=$(resolve_tag uv astral-sh/uv) || return 1
    version=${version#v}

    mkdir -p "$HOME/.local/bin"
    if [ -x "$HOME/.local/bin/uv" ]; then
        installed_version=$("$HOME/.local/bin/uv" --version 2>/dev/null || true)
    fi
    if [ -x "$HOME/.local/bin/uv" ] && [ -x "$HOME/.local/bin/uvx" ] \
        && [[ "$installed_version" == "uv $version"* ]]; then
        echo "uv $version already installed; nothing to do."
        record_lock uv "$version" -
        return 0
    fi

    case "$(uname -m)" in
        x86_64|amd64) platform=x86_64-unknown-linux-gnu ;;
        aarch64|arm64) platform=aarch64-unknown-linux-gnu ;;
        *)
            echo "error: unsupported uv architecture: $(uname -m)" >&2
            return 1
            ;;
    esac
    url="https://github.com/astral-sh/uv/releases/download/${version}/uv-${platform}.tar.gz"
    tmp=$(mktemp -d)
    download "$url" "$tmp/uv.tar.gz" || { rm -rf "$tmp"; return 1; }
    digest=$(sha256_of "$tmp/uv.tar.gz")
    tar xzf "$tmp/uv.tar.gz" -C "$tmp" || { rm -rf "$tmp"; return 1; }
    source_dir="$tmp/uv-${platform}"
    install -m 0755 "$source_dir/uv" "$HOME/.local/bin/uv"
    install -m 0755 "$source_dir/uvx" "$HOME/.local/bin/uvx"
    rm -rf "$tmp"
    [[ "$("$HOME/.local/bin/uv" --version)" == "uv $version"* ]] || return 1
    record_lock uv "$version" "sha256:$digest"
}

ensure_uv() {
    export PATH="$HOME/.local/bin:$PATH"
    install_uv
    export PATH="$HOME/.local/bin:$PATH"
}

# Install a uv tool (latest PyPI release, or the locked version under --locked)
# and record it in the lockfile. uv normalises names with dashes in
# `uv tool list` (e.g. huggingface-hub).
install_uv_tool() {
    local pkg="$1" listed ver spec
    listed=${pkg//_/-}
    if [ "$USE_LOCK" -eq 1 ]; then
        ver=$(lock_version "$listed") || return 1
        spec="${pkg}==${ver}"
    else
        spec="$pkg"
    fi
    uv tool install --force "$spec" || return 1
    ver=$(uv tool list 2>/dev/null | awk -v t="$listed" '$1==t {print $2; exit}')
    record_lock "$listed" "${ver:-unknown}" -
}

# Download a .tar.gz, extract a single named binary into ~/.local/bin, and leave
# the archive's sha256 in TAR_BINARY_DIGEST for the caller to record.
TAR_BINARY_DIGEST=""
install_tar_binary() {
    local name="$1" url="$2"
    local tmp
    tmp=$(mktemp -d)
    download "$url" "$tmp/archive.tar.gz" || { rm -rf "$tmp"; return 1; }
    TAR_BINARY_DIGEST=$(sha256_of "$tmp/archive.tar.gz")
    tar -xzf "$tmp/archive.tar.gz" -C "$tmp" || { rm -rf "$tmp"; return 1; }
    [ -x "$tmp/$name" ] || {
        echo "error: archive does not contain $name" >&2
        rm -rf "$tmp"
        return 1
    }
    mkdir -p "$HOME/.local/bin"
    install -m 0755 "$tmp/$name" "$HOME/.local/bin/$name"
    rm -rf "$tmp"
}

install_precommit() {
    ensure_uv
    install_uv_tool pre-commit
    install_uv_tool detect-secrets

    local os arch gitleaks_platform trufflehog_platform
    os=$(uname -s)
    arch=$(uname -m)
    if [ "$os" != Linux ]; then
        echo "error: precommit binary install currently supports Linux only, got $os" >&2
        return 1
    fi
    case "$arch" in
        x86_64|amd64)
            gitleaks_platform=linux_x64
            trufflehog_platform=linux_amd64
            ;;
        aarch64|arm64)
            gitleaks_platform=linux_arm64
            trufflehog_platform=linux_arm64
            ;;
        *)
            echo "error: unsupported architecture for precommit tools: $arch" >&2
            return 1
            ;;
    esac

    local gitleaks_tag gitleaks_version trufflehog_tag trufflehog_version
    gitleaks_tag=$(resolve_tag gitleaks gitleaks/gitleaks) || return 1
    gitleaks_version=${gitleaks_tag#v}
    gitleaks_tag="v${gitleaks_version}"
    install_tar_binary \
        gitleaks \
        "https://github.com/gitleaks/gitleaks/releases/download/${gitleaks_tag}/gitleaks_${gitleaks_version}_${gitleaks_platform}.tar.gz" \
        || return 1
    record_lock gitleaks "$gitleaks_version" "sha256:$TAR_BINARY_DIGEST"

    trufflehog_tag=$(resolve_tag trufflehog trufflesecurity/trufflehog) || return 1
    trufflehog_version=${trufflehog_tag#v}
    trufflehog_tag="v${trufflehog_version}"
    install_tar_binary \
        trufflehog \
        "https://github.com/trufflesecurity/trufflehog/releases/download/${trufflehog_tag}/trufflehog_${trufflehog_version}_${trufflehog_platform}.tar.gz" \
        || return 1
    record_lock trufflehog "$trufflehog_version" "sha256:$TAR_BINARY_DIGEST"
}

