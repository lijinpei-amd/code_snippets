#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# Sibling lockfile: each install_* records the version/checksum it actually
# resolved, giving a reproducible record on top of the always-latest model.
LOCK_FILE="$SCRIPT_DIR/setup_dev_environment.lock"

path_present() {
    [ -e "$1" ] || [ -L "$1" ]
}

# GNU mv -T prevents a directory destination from silently nesting the source;
# -n preserves anything that appears between the caller's check and the move.
# Because -n reports success when it skips, also require the source to vanish.
move_path_exact_noreplace() {
    local source="$1" destination="$2"

    mv -Tn -- "$source" "$destination" || return 1
    ! path_present "$source"
}

# json_patch FILE [JQ_ARGS...] — atomically apply a jq filter to a JSON file,
# seeding with {} if the file does not exist yet.
json_patch() {
    local file="$1"; shift
    local parent
    parent=$(dirname "$file")
    mkdir -p "$parent"
    local input='{}'
    [ -f "$file" ] && input=$(cat "$file")
    local tmp
    tmp=$(mktemp "$parent/.${file##*/}.XXXXXX")
    if printf '%s' "$input" | jq "$@" > "$tmp"; then
        mv -T -- "$tmp" "$file"
    else
        rm -f "$tmp"
        return 1
    fi
}

# Fetch an artifact over HTTPS. Versions are resolved dynamically to the latest
# upstream release, so there is no pre-reviewed digest to check; TLS is the
# transport trust boundary and record_lock captures what each run installed.
download() {
    local url="$1" output="$2"
    curl --proto '=https' --tlsv1.2 -fSL --retry 3 -o "$output" "$url"
}

# Resolve the latest release tag of a GitHub repo without hitting the rate-limited
# API: the /releases/latest page redirects to /releases/tag/<tag>. Echoes the tag
# verbatim (e.g. "v0.11.7" or "0.11.28").
github_latest_tag() {
    local repo="$1" url tag
    url=$(curl --proto '=https' --tlsv1.2 -fsSL -o /dev/null \
        -w '%{url_effective}' "https://github.com/$repo/releases/latest") \
        || return 1
    # Only trust a URL that actually redirected to a specific tag; a repo with no
    # releases stays on /releases/latest and must be treated as a failure.
    case "$url" in
        */releases/tag/*) tag=${url##*/releases/tag/} ;;
        *)
            echo "error: could not resolve latest release tag for $repo" >&2
            return 1
            ;;
    esac
    printf '%s\n' "$tag"
}

# sha256 of a file, bare hex.
sha256_of() { sha256sum "$1" | awk '{print $1}'; }

# record_lock NAME VERSION [DIGEST] — upsert one component's line in the sibling
# lockfile, leaving other components' lines untouched. DIGEST is "algo:hex" or "-"
# when upstream gives us nothing to hash. Lines are kept sorted so selective
# --components runs produce minimal diffs.
record_lock() {
    local name="$1" version="$2" digest="${3:--}" existing="" prior tmp dir
    dir=$(dirname "$LOCK_FILE")
    mkdir -p "$dir" 2>/dev/null || true
    # The lockfile is a convenience record, not required for the install to
    # succeed. If its directory is not writable (e.g. the script lives in a
    # read-only location), warn and carry on instead of aborting the install.
    if [ ! -w "$dir" ]; then
        echo "warn: $dir not writable; skipping lockfile update for $name" >&2
        return 0
    fi
    if [ -f "$LOCK_FILE" ]; then
        # On a no-op run that passes "-", keep the checksum a prior run recorded
        # so the committed lockfile does not churn between "sha256:..." and "-".
        if [ "$digest" = "-" ]; then
            prior=$(awk -F'\t' -v n="$name" '$1 == n {print $3; exit}' "$LOCK_FILE")
            [ -n "$prior" ] && digest="$prior"
        fi
        # Every component line except this one. A single awk (no grep pipe) keeps
        # a zero-match from tripping `set -o pipefail`.
        existing=$(awk -F'\t' -v n="$name" '!/^#/ && NF && $1 != n' "$LOCK_FILE")
    fi
    tmp=$(mktemp "${LOCK_FILE}.XXXXXX") || {
        echo "warn: could not create temp file in $dir; skipping lockfile update for $name" >&2
        return 0
    }
    {
        printf '# Generated by setup_dev_environment.sh; do not edit by hand.\n'
        printf '# component\tversion\tchecksum\n'
        printf '%s\n%s\t%s\t%s\n' "$existing" "$name" "$version" "$digest" \
            | awk 'NF' | LC_ALL=C sort
    } > "$tmp"
    mv -f -- "$tmp" "$LOCK_FILE"
}

# When USE_LOCK=1 (--locked), installers reproduce the versions recorded in the
# lockfile instead of resolving the latest upstream release.
USE_LOCK=0

# lock_version NAME — echo the version recorded for a component in the lockfile.
# Fails (with a message) if the lockfile or the entry is missing.
lock_version() {
    local name="$1" ver
    [ -f "$LOCK_FILE" ] || {
        echo "error: --locked requires $LOCK_FILE, which does not exist" >&2
        return 1
    }
    ver=$(awk -F'\t' -v n="$name" '$1 == n {print $2; exit}' "$LOCK_FILE")
    [ -n "$ver" ] || {
        echo "error: no lockfile entry for '$name' in $LOCK_FILE" >&2
        return 1
    }
    printf '%s\n' "$ver"
}

# resolve_tag COMPONENT REPO — the version/tag an installer should use: the
# recorded value under --locked, otherwise the latest GitHub release tag. Callers
# normalise the leading "v" as they already do, so both paths stay consistent.
resolve_tag() {
    if [ "$USE_LOCK" -eq 1 ]; then
        lock_version "$1"
    else
        github_latest_tag "$2"
    fi
}

# Verify the ordered primary-key fingerprints in an OpenPGP key or keyring.
# A private temporary GNUPGHOME avoids modifying the user's keyring.
verify_openpgp_fingerprints() {
    local key_file="$1" gnupg_home actual expected
    shift
    gnupg_home=$(mktemp -d)
    chmod 700 "$gnupg_home"
    actual=$(
        GNUPGHOME="$gnupg_home" gpg --batch --show-keys --with-colons "$key_file" 2>/dev/null \
            | awk -F: '$1 == "pub" { want = 1; next } want && $1 == "fpr" { print $10; want = 0 }'
    )
    rm -rf "$gnupg_home"
    expected=$(printf '%s\n' "$@")
    if [ "$actual" != "$expected" ]; then
        echo "error: unexpected OpenPGP primary-key fingerprints in $key_file" >&2
        echo "expected:" >&2
        printf '  %s\n' "$@" >&2
        echo "actual:" >&2
        printf '  %s\n' "$actual" >&2
        return 1
    fi
}

activate_staged_tree() {
    local staged="$1" destination="$2" backup="" backup_root=""
    local parent destination_name transfer transfer_root

    parent=$(dirname "$destination")
    destination_name=${destination##*/}
    mkdir -p "$parent"
    transfer_root=$(mktemp -d "$parent/.activate-stage.XXXXXX")
    transfer="$transfer_root/tree"
    if ! move_path_exact_noreplace "$staged" "$transfer"; then
        rm -rf "$transfer_root"
        return 1
    fi

    if path_present "$destination"; then
        backup_root=$(mktemp -d "$parent/.${destination_name}.backup.XXXXXX")
        backup="$backup_root/tree"
        if ! move_path_exact_noreplace "$destination" "$backup"; then
            if path_present "$backup"; then
                echo "error: destination changed while being moved; previous tree remains at $backup" >&2
            else
                echo "error: could not move existing destination aside: $destination" >&2
            fi
            rm -rf "$transfer_root"
            if ! path_present "$backup"; then
                rm -rf "$backup_root"
            fi
            return 1
        fi
    fi
    if ! move_path_exact_noreplace "$transfer" "$destination"; then
        rm -rf "$transfer_root"
        if [ -n "$backup" ]; then
            if path_present "$destination"; then
                echo "error: destination reappeared during activation; previous tree remains at $backup" >&2
            elif ! move_path_exact_noreplace "$backup" "$destination"; then
                echo "error: activation failed and previous tree could not be restored; it remains at $backup" >&2
            else
                rmdir "$backup_root"
            fi
        fi
        return 1
    fi
    rmdir "$transfer_root"
    [ -z "$backup_root" ] || rm -rf "$backup_root"
}

# ---------------------------------------------------------------------------
# Distro detection + package abstraction
# ---------------------------------------------------------------------------

DISTRO=
APT_UPDATED=0

as_root() {
    if [ "$(id -u)" -eq 0 ]; then
        "$@"
    else
        sudo "$@"
    fi
}

detect_distro() {
    if [ -r /etc/os-release ]; then
        # shellcheck disable=SC1091
        . /etc/os-release
    fi
    case "${ID:-}${ID_LIKE:-}" in
        *arch*)            DISTRO=arch ;;
        *debian*|*ubuntu*) DISTRO=debian ;;
        *)
            if   command -v pacman  >/dev/null 2>&1; then DISTRO=arch
            elif command -v apt-get >/dev/null 2>&1; then DISTRO=debian
            else
                echo "Unsupported distro: cannot find pacman or apt-get" >&2
                exit 1
            fi
            ;;
    esac
}

pkg_name() {
    case "$DISTRO:$1" in
        arch:python3-neovim|arch:python3-pynvim) echo python-pynvim ;;
        arch:silversearcher-ag)                   echo the_silver_searcher ;;
        arch:gh)                                  echo github-cli ;;
        arch:usermod)                             echo shadow ;;
        debian:ninja)                             echo ninja-build ;;
        debian:python3-neovim)                    echo python3-pynvim ;;
        debian:usermod)                           echo passwd ;;
        *)                                        echo "$1" ;;
    esac
}

apt_update_once() {
    [ "$APT_UPDATED" -eq 1 ] && return 0
    as_root apt-get update
    APT_UPDATED=1
}

pkg_install() {
    local pkgs=()
    local p
    for p in "$@"; do pkgs+=("$(pkg_name "$p")"); done
    case "$DISTRO" in
        arch)   as_root pacman -S --needed --noconfirm "${pkgs[@]}" ;;
        debian)
            apt_update_once
            as_root env DEBIAN_FRONTEND=noninteractive apt-get install -y "${pkgs[@]}"
            ;;
    esac
}

