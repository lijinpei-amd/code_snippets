}

install_nvim() {
    # vim-plug's plug.vim is managed by chezmoi (.chezmoiexternal.toml); this
    # installs only the pinned Neovim binary.
    local tag version platform release_url prefix="$HOME/proot/nvim"
    local tmp staged digest installed_version=""

    tag=$(resolve_tag nvim neovim/neovim) || return 1
    version=${tag#v}

    case "$(uname -m)" in
        x86_64|amd64) platform=x86_64 ;;
        aarch64|arm64) platform=arm64 ;;
        *)
            echo "error: unsupported Neovim architecture: $(uname -m)" >&2
            return 1
            ;;
    esac
    release_url="https://github.com/neovim/neovim/releases/download/v${version}/nvim-linux-${platform}.tar.gz"

    if [ -x "$prefix/bin/nvim" ]; then
        installed_version=$("$prefix/bin/nvim" --version 2>/dev/null | sed -n '1p' || true)
    fi
    if [ "$installed_version" != "NVIM v${version}" ]; then
        tmp=$(mktemp -d)
        staged="$tmp/nvim"
        mkdir "$staged"
        download "$release_url" "$tmp/nvim.tar.gz" || { rm -rf "$tmp"; return 1; }
        digest=$(sha256_of "$tmp/nvim.tar.gz")
        tar xzf "$tmp/nvim.tar.gz" --strip-components=1 -C "$staged" \
            || { rm -rf "$tmp"; return 1; }
        [ "$("$staged/bin/nvim" --version | sed -n '1p')" = "NVIM v${version}" ] || {
            echo "error: downloaded Neovim reports an unexpected version" >&2
            rm -rf "$tmp"
            return 1
        }
        activate_staged_tree "$staged" "$prefix" || { rm -rf "$tmp"; return 1; }
        rm -rf "$tmp"
        record_lock nvim "$version" "sha256:$digest"
    else
        record_lock nvim "$version" -
    fi
    export PATH="$prefix/bin:$PATH"
}

config_nvim() {
    local init_lua="$HOME/.config/nvim/init.lua"
    local plug_vim="${XDG_DATA_HOME:-$HOME/.local/share}/nvim/site/autoload/plug.vim"
    if [ ! -f "$init_lua" ]; then
        echo "    (skipping PlugUpdate: $init_lua is not installed; run chezmoi apply first)" >&2
    elif [ -f "$plug_vim" ] && command -v nvim >/dev/null 2>&1; then
        # plug.vim itself is installed from a verified commit in install_nvim;
        # keep that reviewed manager revision unchanged.
        # PlugUpdate also forces existing plugin checkouts to their declared
        # commits; PlugInstall would leave already-present mutable HEADs alone.
        nvim -c 'PlugUpdate --sync' -c qall
    else
        echo "    (skipping PlugUpdate: vim-plug or nvim not installed)" >&2
    fi
}

install_llvm() {
    local v=""
    case "$DISTRO" in
        # pacman installs the current repo version; --locked cannot pin it here.
        arch)   pkg_install llvm clang lld ;;
        debian)
            # Pull llvm.sh from the repo's default branch and run it without a
            # version argument: it installs the current stable LLVM (latest).
            local installer_url="https://raw.githubusercontent.com/opencollab/llvm-jenkins.debian.net/HEAD/llvm.sh"
            local llvm_key_url="https://apt.llvm.org/llvm-snapshot.gpg.key"
            local llvm_key_fingerprint="6084F3CF814B57C1CF12EFD515CF4D18AF4F7421"  # pragma: allowlist secret  gitleaks:allow
            local tmpdir

            pkg_install gnupg lsb-release software-properties-common
            tmpdir=$(mktemp -d)
            download "$llvm_key_url" "$tmpdir/llvm-snapshot.gpg.key" \
                || { rm -rf "$tmpdir"; return 1; }
            # Identity check on the signing key (version-agnostic) is retained.
            verify_openpgp_fingerprints "$tmpdir/llvm-snapshot.gpg.key" "$llvm_key_fingerprint" \
                || { rm -rf "$tmpdir"; return 1; }
            as_root install -m 0644 "$tmpdir/llvm-snapshot.gpg.key" \
                /etc/apt/trusted.gpg.d/apt.llvm.org.asc \
                || { rm -rf "$tmpdir"; return 1; }

            download "$installer_url" "$tmpdir/llvm.sh" \
                || { rm -rf "$tmpdir"; return 1; }
            # Under --locked, install the recorded major version; otherwise pass
            # no version so llvm.sh picks the current stable (latest).
            local locked_v="" llvm_args=()
            if [ "$USE_LOCK" -eq 1 ]; then
                locked_v=$(lock_version llvm) || { rm -rf "$tmpdir"; return 1; }
                llvm_args=("$locked_v")
            fi
            if ! as_root bash "$tmpdir/llvm.sh" "${llvm_args[@]}"; then
                rm -rf "$tmpdir"
                return 1
            fi
            rm -rf "$tmpdir"

            if [ -n "$locked_v" ]; then
                v="$locked_v"
            else
                # Detect the LLVM major version llvm.sh just installed (highest
                # /usr/bin/clang-N) to drive the update-alternatives wiring.
                local clang_bin n
                for clang_bin in /usr/bin/clang-[0-9]*; do
                    [ -e "$clang_bin" ] || continue
                    n="${clang_bin##*/clang-}"
                    case "$n" in *[!0-9]*) continue ;; esac
                    if [ -z "$v" ] || [ "$n" -gt "$v" ]; then v="$n"; fi
                done
            fi
            [ -n "$v" ] || { echo "error: could not detect installed clang version" >&2; return 1; }
            as_root update-alternatives --install /usr/bin/clang   clang   "/usr/bin/clang-$v"   100
            as_root update-alternatives --install /usr/bin/clang++ clang++ "/usr/bin/clang++-$v" 100
            as_root update-alternatives --set clang   "/usr/bin/clang-$v"
            as_root update-alternatives --set clang++ "/usr/bin/clang++-$v"
            # llvm.sh installs lld-$v but only as versioned binaries; clang's
            # -fuse-ld=lld (set by our LLVM_ENABLE_LLD=ON build) searches PATH
            # for an unversioned ld.lld, so wire that up too or linking fails
            # with "invalid linker name in argument '-fuse-ld=lld'".
            as_root update-alternatives --install /usr/bin/ld.lld ld.lld "/usr/bin/ld.lld-$v" 100
            as_root update-alternatives --install /usr/bin/lld    lld    "/usr/bin/lld-$v"    100
            as_root update-alternatives --set ld.lld "/usr/bin/ld.lld-$v"
            as_root update-alternatives --set lld    "/usr/bin/lld-$v"
            ;;
    esac
    if [ -z "$v" ]; then
        v=$(clang --version 2>/dev/null \
            | sed -n 's/.*clang version \([0-9]\+\).*/\1/p' | head -1) || true
    fi
    record_lock llvm "${v:-unknown}" -
}

